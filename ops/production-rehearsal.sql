 a uuid; b uuid; owner_id uuid; qa_booking_id uuid; second_id uuid; guest_id uuid; guest_view jsonb;
 visit date=current_date+60; payload jsonb; made jsonb; denied boolean;
 checks jsonb='[]';
begin
